    /** @param list<array<string, mixed>> $operations */
    private function emitRequestShapes(array $operations): void
    {
        $shapes = [];
        $queue = [];
        foreach ($operations as $op) {
            if ($op['body'] !== null) {
                $queue[] = $op['body'];
            }
        }
        while ($queue !== []) {
            $name = array_pop($queue);
            if (array_key_exists($name, $shapes)) {
                continue;
            }
            $shape = $this->shape($this->schemas[$name], $queue);
            $shapes[$name] = $shape;
        }
        ksort($shapes);
        $code = self::HEADER . "namespace Rask\\Sdk\\Internal;\n\n/**\n * Where a request body holds JSON objects and lists, because a PHP array cannot say which of the two an empty [] is.\n *\n";
        $code .= " * A node is null (a scalar), ['o', [name => node]] (an object), ['m', node] (a map), ['a', node] (a list),\n";
        $code .= " * ['r', schema] (a reference) or ['u', discriminator, [value => schema]] (a union).\n *\n * @internal\n */\nfinal class RequestShapes\n{\n";
        $code .= "    /** @var array<string, array<int, mixed>|null> */\n    public const SCHEMAS = [\n";
        foreach ($shapes as $name => $shape) {
            $code .= '        ' . var_export($name, true) . ' => ' . $this->exportShape($shape) . ",\n";
        }
        $code .= "    ];\n}\n";
        $this->files['src/Internal/RequestShapes.php'] = $code;
    }

    /**
     * @param array<string, mixed> $node
     * @param list<string> $queue
     * @return array<int, mixed>|null
     */
    private function shape(array $node, array &$queue): ?array
    {
        if (isset($node['$ref'])) {
            $name = $this->refName($node);
            if ($this->kind($name) === 'enum') {
                return null;
            }
            $queue[] = $name;
            return ['r', $name];
        }
        if (isset($node['anyOf'])) {
            $branches = array_values(array_filter($node['anyOf'], static fn (array $b): bool => ($b['type'] ?? null) !== 'null'));
            return count($branches) === 1 ? $this->shape($branches[0], $queue) : null;
        }
        if (isset($node['oneOf'])) {
            $variants = [];
            foreach ($node['discriminator']['mapping'] as $value => $reference) {
                $variant = substr($reference, strlen('#/components/schemas/'));
                $variants[$value] = $variant;
                $queue[] = $variant;
            }
            return ['u', $node['discriminator']['propertyName'], $variants];
        }
        $types = array_values(array_diff((array) ($node['type'] ?? []), ['null']));
        if (($types[0] ?? null) === 'array') {
            return ['a', $this->shape($node['items'], $queue)];
        }
        if (($types[0] ?? null) === 'object') {
            if (isset($node['properties'])) {
                $members = [];
                foreach ($node['properties'] as $name => $property) {
                    $child = $this->shape($property, $queue);
                    if ($child !== null) {
                        $members[$name] = $child;
                    }
                }
                return ['o', $members];
            }
            $values = $node['additionalProperties'] ?? null;
            return ['m', is_array($values) ? $this->shape($values, $queue) : null];
        }
        return null;
    }

    private function exportShape(mixed $shape): string
    {
        if (!is_array($shape)) {
            return var_export($shape, true);
        }
        $parts = [];
        $isList = array_is_list($shape);
        foreach ($shape as $key => $value) {
            $parts[] = ($isList ? '' : var_export($key, true) . ' => ') . $this->exportShape($value);
        }
        return '[' . implode(', ', $parts) . ']';
    }

    // ---- doc comments -------------------------------------------------------------------------------------------

    /** @param list<string> $lines */
    private function doc(array $lines, string $indent): string
    {
        $out = [];
        foreach ($lines as $line) {
            if ($line === '' && $out !== [] && end($out) !== '') {
                $out[] = '';
                continue;
            }
            if ($line === '') {
                continue;
            }
            $line = str_replace('*/', '* /', $line);
            if (str_starts_with($line, '@')) {
                $out[] = $line;
                continue;
            }
            foreach (explode("\n", wordwrap($line, 112 - strlen($indent), "\n", false)) as $wrapped) {
                $out[] = $wrapped;
            }
        }
        while ($out !== [] && end($out) === '') {
            array_pop($out);
        }
        if ($out === []) {
            return '';
        }
        if (count($out) === 1) {
            return "$indent/** {$out[0]} */\n";
        }
        $code = "$indent/**\n";
        foreach ($out as $line) {
            $code .= $line === '' ? "$indent *\n" : "$indent * $line\n";
        }
        return $code . "$indent */\n";
    }

    private function firstParagraph(string $text): string
    {
        $paragraph = explode("\n\n", trim($text))[0];
        return trim((string) preg_replace('/\s+/', ' ', $paragraph));
    }

    private function firstSentence(string $text): string
    {
        $paragraph = $this->firstParagraph($text);
        if (preg_match('/^(.{20,}?[.:;])\s/', $paragraph, $match)) {
            return $match[1];
        }
        return $paragraph;
    }
