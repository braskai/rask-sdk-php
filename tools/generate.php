<?php

declare(strict_types=1);

/**
 * Generates the SDK's types and resources from the API v3 contract.
 *
 *     php tools/generate.php                 write src/Model, src/Enum, src/Resource and the two tables in src/Internal
 *     php tools/generate.php --check         fail if the committed files differ from what the contract generates
 *     php tools/generate.php --spec=F --out=D   generate from another contract into another directory
 *
 * Why not Kiota or OpenAPI Generator: see README, "How it is generated". This generator stops on any schema construct
 * it does not know, so a new kind of schema in the contract is a generator failure and not a silently wrong SDK.
 */

final class SdkGenerator
{
    private const HEADER = "<?php\n\ndeclare(strict_types=1);\n\n// Generated by tools/generate.php from spec/openapi.json. Do not edit.\n\n";

    /** Hand-written helpers mixed into a generated resource. */
    private const HELPERS = [
        'Jobs' => 'Rask\\Sdk\\Helper\\WaitsForJobs',
        'Uploads' => 'Rask\\Sdk\\Helper\\UploadsFiles',
    ];

    /** @var array<string, mixed> */
    private array $spec;

    /** @var array<string, array<string, mixed>> */
    private array $schemas;

    /** @var array<string, string> relative path => content */
    private array $files = [];

    /** @var array<string, list<string>> variant class => union interfaces */
    private array $unionsOf = [];

    /** @param array<string, mixed> $spec */
    public function __construct(array $spec)
    {
        $this->spec = $spec;
        $this->schemas = $spec['components']['schemas'];
    }

    /** @return array<string, string> relative path => content */
    public function run(): array
    {
        $operations = $this->operations();
        $models = $this->responseSchemas($operations);
        $this->emitEnums();
        $this->emitUnions($models);
        $this->emitModels($models, $operations);
        $this->emitProblemMembers();
        $this->emitResources($operations);
        $this->emitOperationTable($operations);
        $this->emitRequestShapes($operations);
        ksort($this->files);
        return $this->files;
    }

    // ---- contract reading ---------------------------------------------------------------------------------------

    /** @return list<array<string, mixed>> */
    private function operations(): array
    {
        $operations = [];
        foreach ($this->spec['paths'] as $path => $item) {
            foreach (['get', 'post', 'put', 'patch', 'delete'] as $method) {
                if (!isset($item[$method])) {
                    continue;
                }
                $operations[] = $this->operation($path, $method, $item[$method], $item['parameters'] ?? []);
            }
        }
        usort($operations, static fn (array $a, array $b): int => strcmp($a['id'], $b['id']));
        return $operations;
    }

    /**
     * @param array<string, mixed> $op
     * @param list<array<string, mixed>> $shared
     * @return array<string, mixed>
     */
    private function operation(string $path, string $method, array $op, array $shared): array
    {
        $id = $op['operationId'] ?? throw new RuntimeException("$method $path has no operationId");
        $params = ['path' => [], 'query' => [], 'header' => []];
        foreach ([...$shared, ...($op['parameters'] ?? [])] as $raw) {
            $param = $this->deref($raw);
            $params[$param['in']][] = $param;
        }
        $headerNames = array_map(static fn (array $p): string => $p['name'], $params['header']);
        // The header parameter decides, not x-rask-operation.etag: mergeSegments says required there and takes per-segment
        // ETags in its body, with no If-Match header at all.
        $ifMatch = 'none';
        foreach ($params['header'] as $param) {
            if ($param['name'] === 'If-Match') {
                $ifMatch = ($param['required'] ?? false) ? 'required' : 'optional';
            }
        }
        foreach ($headerNames as $name) {
            if (!in_array($name, ['Idempotency-Key', 'If-Match', 'If-None-Match'], true)) {
                throw new RuntimeException("$id: header parameter $name is not handled");
            }
        }

        $success = [];
        foreach ($op['responses'] as $status => $response) {
            if ((int) $status >= 200 && (int) $status < 300) {
                $success[(int) $status] = $this->deref($response);
            }
        }
        if (count($success) !== 1) {
            throw new RuntimeException("$id: expected one 2xx response");
        }
        $status = array_key_first($success);
        $response = $success[$status];
        $returns = null;
        if (isset($response['content'])) {
            $schema = $response['content']['application/json']['schema'] ?? throw new RuntimeException("$id: non-JSON success");
            $returns = $this->refName($schema);
            if ($this->kind($returns) !== 'object') {
                throw new RuntimeException("$id: a response of kind {$this->kind($returns)} is not handled");
            }
        }

        $body = null;
        $bodyRequired = false;
        if (isset($op['requestBody'])) {
            $requestBody = $this->deref($op['requestBody']);
            $schema = $requestBody['content']['application/json']['schema'] ?? throw new RuntimeException("$id: non-JSON request");
            $body = $this->refName($schema);
            $bodyRequired = (bool) ($requestBody['required'] ?? false);
        }

        $meta = $op['x-rask-operation'];
        return [
            'id' => $id,
            'method' => strtoupper($method),
            'path' => $path,
            'tag' => $op['tags'][0],
            'summary' => $op['summary'] ?? $id,
            'description' => $op['description'] ?? '',
            'deprecated' => (bool) ($op['deprecated'] ?? false),
            'path_params' => $params['path'],
            'query_params' => $params['query'],
            'idempotency' => $meta['idempotency_key'],
            'if_match' => $ifMatch,
            'if_none_match' => in_array('If-None-Match', $headerNames, true),
            'body' => $body,
            'body_required' => $bodyRequired,
            'status' => $status,
            'returns' => $returns,
            'paginated' => $meta['pagination'] === 'cursor',
        ];
    }

    /**
     * @param array<string, mixed> $node
     * @return array<string, mixed>
     */
    private function deref(array $node): array
    {
        while (isset($node['$ref'])) {
            $target = $this->spec;
            foreach (array_slice(explode('/', $node['$ref']), 1) as $part) {
                $target = $target[$part];
            }
            $node = $target;
        }
        return $node;
    }

    /** @param array<string, mixed> $node */
    private function refName(array $node): string
    {
        if (!isset($node['$ref'])) {
            throw new RuntimeException('Expected a $ref: ' . json_encode($node));
        }
        return substr($node['$ref'], strlen('#/components/schemas/'));
    }

    private function kind(string $schema): string
    {
        $node = $this->schemas[$schema] ?? throw new RuntimeException("Unknown schema $schema");
        if (isset($node['oneOf'])) {
            return 'union';
        }
        if (isset($node['enum'])) {
            return 'enum';
        }
        if (($node['type'] ?? null) === 'object') {
            return isset($node['properties']) ? 'object' : 'map';
        }
        throw new RuntimeException("Schema $schema has a form this generator does not know");
    }

    /**
     * Reduces a property schema to what the PHP type needs.
     *
     * @param array<string, mixed> $node
     * @return array{kind: string, nullable: bool, name?: string, item?: array<string, mixed>}
     */
    private function describe(array $node): array
    {
        if (isset($node['$ref'])) {
            $name = $this->refName($node);
            return match ($this->kind($name)) {
                'enum' => ['kind' => 'string', 'nullable' => false, 'enum' => $name],
                'object' => ['kind' => 'model', 'nullable' => false, 'name' => $name],
                'union' => ['kind' => 'union', 'nullable' => false, 'name' => $name],
                'map' => $this->describeMap($this->schemas[$name]),
            };
        }
        if (isset($node['anyOf'])) {
            $branches = array_values(array_filter($node['anyOf'], static fn (array $b): bool => ($b['type'] ?? null) !== 'null'));
            if (count($branches) !== 1) {
                throw new RuntimeException('An anyOf with several non-null branches is not handled: ' . json_encode($node));
            }
            return ['nullable' => true] + $this->describe($branches[0]);
        }
        if (isset($node['oneOf'])) {
            throw new RuntimeException('An inline oneOf is not handled: ' . json_encode($node));
        }
        $types = (array) ($node['type'] ?? throw new RuntimeException('A schema without a type: ' . json_encode($node)));
        $nullable = in_array('null', $types, true);
        $types = array_values(array_diff($types, ['null']));
        if (count($types) !== 1) {
            throw new RuntimeException('A multi-typed schema is not handled: ' . json_encode($node));
        }
        return match ($types[0]) {
            'string' => ['kind' => 'string', 'nullable' => $nullable],
            'integer' => ['kind' => 'int', 'nullable' => $nullable],
            'number' => ['kind' => 'float', 'nullable' => $nullable],
            'boolean' => ['kind' => 'bool', 'nullable' => $nullable],
            'array' => ['kind' => 'list', 'nullable' => $nullable, 'item' => $this->describe($node['items'])],
            'object' => ['nullable' => $nullable] + $this->describeMap($node),
            default => throw new RuntimeException("Type {$types[0]} is not handled"),
        };
    }

    /**
     * @param array<string, mixed> $node
     * @return array{kind: string, nullable: bool, item?: array<string, mixed>}
     */
    private function describeMap(array $node): array
    {
        if (isset($node['properties'])) {
            throw new RuntimeException('An inline object with properties is not handled: ' . json_encode($node));
        }
        $values = $node['additionalProperties'] ?? true;
        if (!is_array($values)) {
            return ['kind' => 'map', 'nullable' => false];
        }
        return ['kind' => 'map', 'nullable' => false, 'item' => $this->describe($values)];
    }

    /**
     * @param list<array<string, mixed>> $operations
     * @return array<string, true> object and union schemas a response can hold
     */
    private function responseSchemas(array $operations): array
    {
        $seen = [];
        $queue = ['Problem'];
        foreach ($operations as $operation) {
            if ($operation['returns'] !== null) {
                $queue[] = $operation['returns'];
            }
        }
        while ($queue !== []) {
            $name = array_pop($queue);
            if (isset($seen[$name])) {
                continue;
            }
            $seen[$name] = true;
            $schema = $this->schemas[$name];
            if (isset($schema['oneOf'])) {
                foreach ($schema['oneOf'] as $branch) {
                    $queue[] = $this->refName($branch);
                }
                continue;
            }
            foreach ($schema['properties'] ?? [] as $property) {
                array_push($queue, ...$this->referencedSchemas($this->describe($property)));
            }
        }
        ksort($seen);
        return $seen;
    }

    /**
     * @param array<string, mixed> $type
     * @return list<string>
     */
    private function referencedSchemas(array $type): array
    {
        if (isset($type['item'])) {
            return $this->referencedSchemas($type['item']);
        }
        return isset($type['name']) ? [$type['name']] : [];
    }

    // ---- enums --------------------------------------------------------------------------------------------------

    private function emitEnums(): void
    {
        foreach ($this->schemas as $name => $schema) {
            if (!isset($schema['enum'])) {
                continue;
            }
            $notes = [];
            if (preg_match_all('/^- `([^`]+)`: (.+)$/m', $schema['description'] ?? '', $matches, PREG_SET_ORDER)) {
                foreach ($matches as $match) {
                    $notes[$match[1]] = $match[2];
                }
            }
            $code = self::HEADER . "namespace Rask\\Sdk\\Enum;\n\n";
            $note = "Values of the API's `$name`.";
            if ($schema['x-rask-open-enum'] ?? false) {
                $note .= ' Open: a later API version may send a value that is not listed here, and it reaches you unchanged.';
            }
            $code .= $this->doc([$this->firstParagraph($schema['description'] ?? ''), $note], '');
            $code .= "final class $name\n{\n";
            $names = [];
            foreach ($schema['enum'] as $value) {
                if ($value === null) {
                    continue;
                }
                $constant = $this->constantName((string) $value, $names);
                $names[] = $constant;
                if (isset($notes[$value])) {
                    $code .= $this->doc([$notes[$value]], '    ');
                }
                $code .= "    public const $constant = " . var_export($value, true) . ";\n\n";
            }
            $code .= "    /** Every value this SDK version knows. */\n";
            $code .= "    public const KNOWN = [\n";
            foreach ($names as $constant) {
                $code .= "        self::$constant,\n";
            }
            $code .= "    ];\n\n    private function __construct()\n    {\n    }\n}\n";
            $this->files["src/Enum/$name.php"] = $code;
        }
    }

    /** @param list<string> $taken */
    private function constantName(string $value, array $taken): string
    {
        $constant = strtoupper(trim((string) preg_replace('/[^A-Za-z0-9]+/', '_', $value), '_'));
        if ($constant === '' || ctype_digit($constant[0]) || $constant === 'CLASS') {
            $constant = 'V_' . $constant;
        }
        while (in_array($constant, $taken, true)) {
            $constant .= '_';
        }
        return $constant;
    }

    // ---- unions -------------------------------------------------------------------------------------------------

    /** @param array<string, true> $models */
    private function emitUnions(array $models): void
    {
        $table = [];
        $unions = [];
        foreach (array_keys($models) as $name) {
            $schema = $this->schemas[$name];
            if (!isset($schema['oneOf'])) {
                continue;
            }
            $unions[] = $name;
            $discriminator = $schema['discriminator'] ?? throw new RuntimeException("Union $name has no discriminator");
            $variants = [];
            foreach ($discriminator['mapping'] as $value => $reference) {
                $variant = substr($reference, strlen('#/components/schemas/'));
                $variants[$value] = $variant;
                $this->unionsOf[$variant][] = $name;
            }
            $table[$name] = [$discriminator['propertyName'], $variants];

            $classes = array_values(array_unique($variants));
            sort($classes);
            $code = self::HEADER . "namespace Rask\\Sdk\\Model;\n\nuse Rask\\Sdk\\Core\\UnionMember;\n\n";
            $code .= $this->doc([
                $this->firstParagraph($schema['description'] ?? ''),
                "Narrow it with instanceof: " . implode(', ', $classes) . ", or UnknownVariant for a variant this SDK version does not know (nothing is lost: read it with toArray()).",
            ], '');
            $code .= "interface $name extends UnionMember\n{\n}\n";
            $this->files["src/Model/$name.php"] = $code;
        }
        foreach ($this->unionsOf as &$list) {
            $list = array_values(array_unique($list));
            sort($list);
        }
        unset($list);

        $code = self::HEADER . "namespace Rask\\Sdk\\Internal;\n\n";
        $code .= "/** @internal */\nfinal class Unions\n{\n";
        $code .= "    /** @var array<string, array{0: string, 1: array<string, class-string<\\Rask\\Sdk\\Core\\Model>>}> union interface => [discriminator, value => variant class] */\n";
        $code .= "    public const TABLE = [\n";
        foreach ($table as $name => [$property, $variants]) {
            $code .= "        \\Rask\\Sdk\\Model\\$name::class => [" . var_export($property, true) . ", [\n";
            foreach ($variants as $value => $variant) {
                $code .= '            ' . var_export($value, true) . " => \\Rask\\Sdk\\Model\\$variant::class,\n";
            }
            $code .= "        ]],\n";
        }
        $code .= "    ];\n}\n";
        $this->files['src/Internal/Unions.php'] = $code;

        $code = self::HEADER . "namespace Rask\\Sdk\\Model;\n\nuse Rask\\Sdk\\Core\\Model;\n\n";
        $code .= $this->doc([
            'A union variant this SDK version does not know, kept whole: toArray(), get() and array access read every field.',
        ], '');
        $code .= "final class UnknownVariant extends Model implements " . implode(', ', $unions) . "\n{\n}\n";
        $this->files['src/Model/UnknownVariant.php'] = $code;
    }

    // ---- models -------------------------------------------------------------------------------------------------

    /**
     * @param array<string, true> $models
     * @param list<array<string, mixed>> $operations
     */
    private function emitModels(array $models, array $operations): void
    {
        foreach ($operations as $operation) {
            if ($operation['paginated'] && !isset($this->schemas[$operation['returns']]['properties']['next_cursor'])) {
                throw new RuntimeException("{$operation['id']} is paginated but its response has no next_cursor");
            }
        }
        foreach (array_keys($models) as $name) {
            $schema = $this->schemas[$name];
            if (isset($schema['oneOf'])) {
                continue;
            }
            // The list envelope, paginated or in one page: foreach works on both.
            $isPage = isset($schema['properties']['data'], $schema['properties']['next_cursor']);
            $this->files["src/Model/$name.php"] = $this->modelClass($name, $schema, $isPage);
        }
    }

    /** Types for the Problem members that $e->name reads, so that IDEs and PHPStan know them. */
    private function emitProblemMembers(): void
    {
        $schema = $this->schemas['Problem'];
        $declared = ['type', 'title', 'status', 'detail', 'instance', 'code', 'retryable', 'retry', 'recommendation', 'hint', 'errors'];
        $lines = ['The Problem members that vary by code. RaskError::__get() reads them, and any member this SDK version does not know.', ''];
        foreach ($schema['properties'] as $name => $property) {
            if (!in_array($name, $declared, true)) {
                $lines[] = '@property-read ' . $this->docType($this->describe($property)) . "|null \$$name";
            }
        }
        $code = self::HEADER . "namespace Rask\\Sdk\\Exception;\n\nuse Rask\\Sdk\\Model\\ActiveJobRef;\n\n";
        $code .= $this->doc($lines, '');
        $code .= "abstract class ProblemMembers extends \\RuntimeException\n{\n}\n";
        $this->files['src/Exception/ProblemMembers.php'] = $code;
    }

    /** @param array<string, mixed> $schema */
    private function modelClass(string $name, array $schema, bool $isPage): string
    {
        foreach (['Model', 'CursorPage', 'Decode', 'RawResponse'] as $reserved) {
            if ($name === $reserved) {
                throw new RuntimeException("Schema name $name collides with an SDK class");
            }
        }
        $base = $isPage ? 'CursorPage' : 'Model';
        $code = self::HEADER . "namespace Rask\\Sdk\\Model;\n\n";
        $code .= "use Rask\\Sdk\\Core\\$base;\nuse Rask\\Sdk\\Core\\RawResponse;\nuse Rask\\Sdk\\Internal\\Decode;\n\n";
        $lines = [$this->firstParagraph($schema['description'] ?? '')];
        if ($schema['deprecated'] ?? false) {
            $lines[] = '@deprecated';
        }
        $itemType = null;
        if ($isPage) {
            $itemType = $this->describe($schema['properties']['data']['items'] ?? throw new RuntimeException("Page $name has no data"));
            $lines[] = '@extends CursorPage<' . $this->docType($itemType) . '>';
        }
        $code .= $this->doc($lines, '');
        $implements = $this->unionsOf[$name] ?? [];
        $code .= "final class $name extends $base" . ($implements === [] ? '' : ' implements ' . implode(', ', $implements)) . "\n{\n";

        $properties = $schema['properties'] ?? [];
        $code .= '    protected const FIELDS = [';
        $code .= implode(', ', array_map(static fn (string $p): string => var_export($p, true), array_keys($properties)));
        $code .= "];\n\n";

        $assignments = '';
        foreach ($properties as $property => $node) {
            if (!preg_match('/^[a-zA-Z_][a-zA-Z0-9_]*$/', $property)) {
                throw new RuntimeException("$name.$property cannot be a PHP property");
            }
            $type = $this->describe($node);
            $doc = [$this->firstSentence($this->deref($node)['description'] ?? ($node['description'] ?? ''))];
            if (isset($type['enum'])) {
                $doc[] = "@see \\Rask\\Sdk\\Enum\\{$type['enum']}";
            }
            if ($node['deprecated'] ?? false) {
                $doc[] = '@deprecated';
            }
            $doc[] = '@var ' . $this->docType($type) . '|null';
            $code .= $this->doc($doc, '    ');
            $code .= '    public readonly ' . $this->nativeType($type) . " \$$property;\n\n";
            $assignments .= "        \$this->$property = " . $this->decodeExpression($type, "\$data['$property'] ?? null") . ";\n";
        }

        if ($properties !== []) {
            $code .= "    /** @param array<array-key, mixed> \$data */\n";
            $code .= "    public function __construct(array \$data = [], ?RawResponse \$response = null)\n    {\n";
            $code .= "        parent::__construct(\$data, \$response);\n";
            $code .= $assignments;
            $code .= "    }\n";
        }
        if ($isPage) {
            $code .= "\n    public function items(): array\n    {\n        return \$this->data ?? [];\n    }\n";
        }
        $code = rtrim($code) . "\n}\n";
        return $code;
    }

    /** @param array<string, mixed> $type */
    private function nativeType(array $type): string
    {
        return match ($type['kind']) {
            'string' => '?string',
            'int' => '?int',
            'float' => '?float',
            'bool' => '?bool',
            'model', 'union' => '?' . $type['name'],
            'list', 'map' => '?array',
        };
    }

    /** @param array<string, mixed> $type */
    private function docType(array $type): string
    {
        return match ($type['kind']) {
            'string' => 'string',
            'int' => 'int',
            'float' => 'float',
            'bool' => 'bool',
            'model', 'union' => $type['name'],
            'list' => 'list<' . $this->itemDocType($type['item']) . '>',
            'map' => 'array<string, ' . (isset($type['item']) ? $this->itemDocType($type['item']) : 'mixed') . '>',
        };
    }

    /** @param array<string, mixed> $type */
    private function itemDocType(array $type): string
    {
        return $this->docType($type) . (($type['nullable'] ?? false) ? '|null' : '');
    }

    /** @param array<string, mixed> $type */
    private function decodeExpression(array $type, string $value): string
    {
        switch ($type['kind']) {
            case 'string':
            case 'int':
            case 'float':
            case 'bool':
                return "Decode::{$type['kind']}($value)";
            case 'model':
                return "Decode::model($value, {$type['name']}::class)";
            case 'union':
                return "Decode::union($value, {$type['name']}::class)";
            case 'list':
                $item = $type['item'];
                if (($item['nullable'] ?? false) && $item['kind'] === 'string') {
                    return "Decode::nullableStrings($value)";
                }
                if ($item['nullable'] ?? false) {
                    throw new RuntimeException('A list of nullable ' . $item['kind'] . ' is not handled');
                }
                return match ($item['kind']) {
                    'string' => "Decode::strings($value)",
                    'int' => "Decode::ints($value)",
                    'float' => "Decode::floats($value)",
                    'model' => "Decode::models($value, {$item['name']}::class)",
                    'union' => "Decode::unions($value, {$item['name']}::class)",
                    default => throw new RuntimeException('A list of ' . $item['kind'] . ' is not handled'),
                };
            case 'map':
                if (isset($type['item']) && $type['item']['kind'] === 'string') {
                    return "Decode::stringMap($value)";
                }
                if (isset($type['item'])) {
                    throw new RuntimeException('A map of ' . $type['item']['kind'] . ' is not handled');
                }
                return "Decode::map($value)";
        }
        throw new RuntimeException('Unknown kind ' . $type['kind']);
    }

    // ---- resources ----------------------------------------------------------------------------------------------

    /** @param list<array<string, mixed>> $operations */
    private function emitResources(array $operations): void
    {
        $groups = [];
        foreach ($operations as $operation) {
            $groups[$this->resourceClass($operation['tag'])][] = $operation;
        }
        ksort($groups);
        foreach ($groups as $class => $members) {
            $code = self::HEADER . "namespace Rask\\Sdk\\Resource;\n\n";
            $imports = ['Rask\\Sdk\\Core\\Resource' => true];
            foreach ($members as $operation) {
                if ($operation['returns'] === null) {
                    $imports['Rask\\Sdk\\Core\\RawResponse'] = true;
                } elseif ($operation['returns'] === $class) {
                    // $rask->media returns a Media: the resource class and the model share a short name.
                    $imports["Rask\\Sdk\\Model\\$class as {$class}Model"] = true;
                } else {
                    $imports['Rask\\Sdk\\Model\\' . $operation['returns']] = true;
                }
            }
            if (isset(self::HELPERS[$class])) {
                $imports[self::HELPERS[$class]] = true;
            }
            ksort($imports);
            foreach (array_keys($imports) as $import) {
                $code .= "use $import;\n";
            }
            $code .= "\n" . $this->doc(["The API's `{$members[0]['tag']}` operations."], '');
            $code .= "final class $class extends Resource\n{\n";
            if (isset(self::HELPERS[$class])) {
                $code .= '    use ' . substr(strrchr(self::HELPERS[$class], '\\'), 1) . ";\n\n";
            }
            $methods = array_map(fn (array $operation): string => $this->method($operation, $class), $members);
            $code .= implode("\n", $methods);
            $code .= "}\n";
            $this->files["src/Resource/$class.php"] = $code;
        }

        $code = self::HEADER . "namespace Rask\\Sdk\\Internal;\n\n";
        $classes = array_keys($groups);
        foreach ($classes as $class) {
            $code .= "use Rask\\Sdk\\Resource\\$class;\n";
        }
        $code .= "\n/** @internal */\ntrait ResourceProperties\n{\n";
        foreach ($classes as $class) {
            $code .= "    public readonly $class \$" . lcfirst($class) . ";\n";
        }
        $code .= "\n    private function initResources(Transport \$transport): void\n    {\n";
        foreach ($classes as $class) {
            $code .= '        $this->' . lcfirst($class) . " = new $class(\$transport);\n";
        }
        $code .= "    }\n}\n";
        $this->files['src/Internal/ResourceProperties.php'] = $code;
    }

    private function resourceClass(string $tag): string
    {
        return str_replace(' ', '', ucwords($tag));
    }

    /** @param array<string, mixed> $op */
    private function method(array $op, string $resourceClass): string
    {
        $params = [];
        $docParams = [];
        $pathArgs = [];
        foreach ($op['path_params'] as $param) {
            $phpName = lcfirst(str_replace('_', '', ucwords($param['name'], '_')));
            $type = $this->describe($param['schema']);
            $native = $type['kind'] === 'int' ? 'int' : 'string';
            $params[] = ['code' => "$native \$$phpName", 'optional' => false];
            $docParams[] = "@param $native \$$phpName " . $this->firstSentence($param['description'] ?? '');
            $pathArgs[] = var_export($param['name'], true) . " => \$$phpName";
        }

        $hasBody = $op['body'] !== null;
        $hasQuery = $op['query_params'] !== [];
        if ($hasBody) {
            $params[] = ['code' => 'array $body', 'optional' => !$op['body_required'], 'default' => '[]'];
            $docParams[] = '@param ' . $this->requestDocType($this->schemas[$op['body']], 0) . ' $body';
        }
        if ($hasQuery) {
            $required = (bool) array_filter($op['query_params'], static fn (array $p): bool => (bool) ($p['required'] ?? false));
            $params[] = ['code' => 'array $query', 'optional' => !$required, 'default' => '[]'];
            $docParams[] = '@param ' . $this->queryDocType($op['query_params']) . ' $query';
        }
        $optionsRequired = $op['if_match'] === 'required';
        $params[] = ['code' => 'array $options', 'optional' => !$optionsRequired, 'default' => '[]'];
        $docParams[] = '@param ' . $this->optionsDocType($op) . ' $options';

        // PHP deprecates an optional parameter before a required one: a default survives only behind no required one.
        $seenRequired = false;
        foreach (array_reverse(array_keys($params)) as $index) {
            if (!$params[$index]['optional']) {
                $seenRequired = true;
            } elseif ($seenRequired) {
                $params[$index]['optional'] = false;
            }
        }
        $signature = implode(', ', array_map(
            static fn (array $p): string => $p['code'] . ($p['optional'] ? " = {$p['default']}" : ''),
            $params,
        ));

        $returns = $op['returns'] ?? 'RawResponse';
        if ($returns === $resourceClass) {
            $returns .= 'Model';
        }
        $lines = [$op['summary'] . '.', ''];
        $paragraph = $this->firstParagraph($op['description']);
        if ($paragraph !== '') {
            $lines[] = $paragraph;
            $lines[] = '';
        }
        if ($op['deprecated']) {
            $lines[] = '@deprecated This operation is deprecated by the API; see its documentation for the replacement.';
        }
        $lines[] = '';
        array_push($lines, ...$docParams);
        $lines[] = '@throws \\Rask\\Sdk\\Exception\\RaskError';
        $lines[] = '@throws \\Rask\\Sdk\\Exception\\UsageError';

        $call = sprintf(
            '$this->transport->call(%s, [%s], %s, %s, $options)',
            var_export($op['id'], true),
            implode(', ', $pathArgs),
            $hasQuery ? '$query' : '[]',
            $hasBody ? '$body' : 'null',
        );

        $code = $this->doc($lines, '    ');
        $code .= "    public function {$op['id']}($signature): $returns\n    {\n";
        if ($op['returns'] === null) {
            $code .= "        return $call;\n";
        } else {
            $code .= "        \$response = $call;\n\n";
            if ($op['paginated']) {
                $pathPass = array_map(static fn (string $arg): string => substr($arg, (int) strpos($arg, '$')), $pathArgs);
                $nextArgs = implode(', ', [...$pathPass, "['cursor' => \$cursor] + \$query", '$options']);
                $code .= "        return (new $returns(\$response->json(), \$response))->withNextPage(\n";
                $code .= "            fn (string \$cursor): $returns => \$this->{$op['id']}($nextArgs),\n";
                $code .= "        );\n";
            } else {
                $code .= "        return new $returns(\$response->json(), \$response);\n";
            }
        }
        $code .= "    }\n";
        return $code;
    }

    /** @param list<array<string, mixed>> $params */
    private function queryDocType(array $params): string
    {
        $members = [];
        foreach ($params as $param) {
            $members[] = $param['name'] . (($param['required'] ?? false) ? '' : '?') . ': ' . $this->requestDocType($param['schema'], 2);
        }
        return 'array{' . implode(', ', $members) . '}';
    }

    /** @param array<string, mixed> $op */
    private function optionsDocType(array $op): string
    {
        $members = [];
        if ($op['if_match'] === 'required') {
            $members[] = 'if_match: string';
        } elseif ($op['if_match'] === 'optional') {
            $members[] = 'if_match?: string';
        }
        if ($op['idempotency'] !== 'none') {
            $members[] = 'idempotency_key?: string';
        }
        if ($op['if_none_match']) {
            $members[] = 'if_none_match?: string';
        }
        return 'array{' . implode(', ', $members) . '}';
    }

    /** @param array<string, mixed> $node */
    private function requestDocType(array $node, int $depth): string
    {
        if (isset($node['$ref'])) {
            return $this->requestDocType($this->deref($node), $depth);
        }
        if (isset($node['anyOf'])) {
            $branches = array_values(array_filter($node['anyOf'], static fn (array $b): bool => ($b['type'] ?? null) !== 'null'));
            return $this->requestDocType($branches[0], $depth);
        }
        if (isset($node['oneOf'])) {
            return 'array<string, mixed>';
        }
        if (isset($node['enum'])) {
            return 'string';
        }
        $types = array_values(array_diff((array) ($node['type'] ?? []), ['null']));
        switch ($types[0] ?? null) {
            case 'string':
                return 'string';
            case 'integer':
                return 'int';
            case 'number':
                return 'int|float';
            case 'boolean':
                return 'bool';
            case 'array':
                return 'list<' . $this->requestDocType($node['items'], $depth + 1) . '>';
            case 'object':
                if (!isset($node['properties'])) {
                    $values = $node['additionalProperties'] ?? null;
                    return 'array<string, ' . (is_array($values) ? $this->requestDocType($values, $depth + 1) : 'mixed') . '>';
                }
                if ($node['properties'] === []) {
                    return 'array{}';
                }
                if ($depth >= 3) {
                    return 'array<string, mixed>';
                }
                $members = [];
                $required = $node['required'] ?? [];
                foreach ($node['properties'] as $name => $property) {
                    $members[] = $name . (in_array($name, $required, true) ? '' : '?') . ': ' . $this->requestDocType($property, $depth + 1);
                }
                return 'array{' . implode(', ', $members) . '}';
        }
        return 'mixed';
    }

